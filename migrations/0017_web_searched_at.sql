-- 0017_web_searched_at.sql — 웹 자료를 마지막으로 찾은 시각
--
-- "정보 다시 찾기" 가 웹 검색까지 다시 돌리게 되면서 필요해졌다. 한 번의 조사 안에서
-- 조사 계획을 여러 번 세우는 경로가 있기 때문이다.
--
--   * 릴레이는 모델이 응답하지 않으면 다른 모델로 계획을 다시 받는다
--   * 무료 등급 Gemini 키는 내장 검색에 429 를 내서, 검색을 끄고 계획을 다시 받는다
--
-- 그때마다 웹 검색을 다시 돌리면 부모가 버튼을 한 번 눌렀는데 크레딧이 두세 번 나간다.
-- 이 시각이 `searched_at` 보다 새것이면 "이번 조사에서 이미 찾았다" 는 뜻이라 건너뛴다.

ALTER TABLE books ADD COLUMN web_searched_at TEXT;
