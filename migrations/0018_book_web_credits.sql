-- 0018_book_web_credits.sql — 책 한 권이 쓴 웹 검색 크레딧
--
-- 책당 상한을 **횟수에서 크레딧으로** 바꾼다.
--
-- 횟수(6회)로 막던 것은 두 가지가 어긋났다.
--   * 한 번의 `search` 가 1~2 크레딧을 쓴다(basic 1, advanced 2). 횟수로는 실제로 얼마를
--     썼는지 알 수 없다.
--   * 읽기 난이도 전용 검색도 1 크레딧을 쓰는데 그건 횟수에 세지 않았다.
--
-- 이제 실제로 쓴 크레딧을 세고 책당 50 으로 막는다. 넉넉히 다시 찾아 근거를 쌓을 수 있는
-- 값이면서(한 번에 1~3), 한 권이 월 예산을 통째로 먹지 못하게 한다.
--
-- `web_searches` 는 남긴다. 그것은 상한이 아니라 **질의 사다리의 칸 번호**로 쓴다
-- (`search/tavily.ts` 의 `buildQuery`) — 다시 찾을 때마다 다른 말로 묻기 위한 값이다.

ALTER TABLE books ADD COLUMN web_credits INTEGER NOT NULL DEFAULT 0;
