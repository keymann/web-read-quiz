-- 표지 사진을 **똑바로 세우기 위해 아직 남은 회전량**(시계 방향, 도).
--
-- 부모는 책을 손에 들고 사진을 찍는다. 눕혀 찍거나 폰을 가로로 들면 제목이 옆으로 누운
-- 사진이 등록된다. EXIF 방향은 브라우저가 이미 바로잡아 주지만, 그건 "폰이 어떻게 들렸는가"
-- 일 뿐 "책이 어느 쪽으로 누웠는가" 는 아니다. 그건 사진을 봐야 안다.
--
-- 값의 뜻:
--   NULL  아직 확인하지 않았다 (이 컬럼이 생기기 전에 등록된 책)
--   0     똑바로 서 있다
--   90 · 180 · 270  이만큼 시계 방향으로 더 돌려야 제목이 바로 읽힌다
--
-- 회전은 브라우저가 한다 — Workers 런타임에는 이미지 디코더가 없다. 브라우저가 돌린 바이트를
-- 다시 올리면 서버가 0 으로 되돌린다. 그래서 0 이 아닌 값은 "돌려야 하는데 아직 못 돌렸다" 는
-- 뜻이고, 다음에 부모가 그 책을 열 때 다시 시도된다.
ALTER TABLE books ADD COLUMN cover_rotation INTEGER
	CHECK (cover_rotation IS NULL OR cover_rotation IN (0, 90, 180, 270));
