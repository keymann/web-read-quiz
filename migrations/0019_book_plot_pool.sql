-- 0019_book_plot_pool.sql — 지금까지 쌓은 줄거리
--
-- "정보 다시 찾기" 는 줄거리를 **쌓는 일**이다. 그런데 그것을 프롬프트로만 부탁하고 있었다 —
-- `[지금까지 정리한 줄거리]` 를 되돌려 주며 "지우지 말고 보강하라" 고 시키는 방식이다.
-- 모델은 그 말을 자주 흘렸다. 실제로 다시 찾을 때마다 줄거리가 **통째로 새 것으로 갈렸고**,
-- 이번 자료가 지난 자료보다 얇으면 줄거리가 오히려 짧아졌다. 부모가 버튼을 누른 뜻과 반대다.
--
-- 그래서 서버가 직접 쌓는다(`services/plot.ts` 의 `mergePlot`). 쌓은 결과를 여기 둔다.
--
-- `brief` 로 대신할 수 없다. 그 안의 `[줄거리]` 절에는 부모가 직접 적은 줄거리도 함께 들어
-- 있어서(`manual_plot`), 그것을 되돌려 쌓으면 부모가 자기 글을 고쳤을 때 지운 문장이 영영
-- 남는다. AI 가 모은 것과 부모가 적은 것은 따로 두어야 각자 고칠 수 있다.
--
-- 이 컬럼이 비어 있는 옛 행은 `brief` 의 `[줄거리]` 에서 부모 글을 떼어내 첫 밑감으로 쓴다
-- (`services/book.ts` 의 `knownPlot`). 그래서 이미 쌓아 둔 책도 다시 찾기에서 잃지 않는다.

ALTER TABLE books ADD COLUMN ai_plot TEXT;
